# shellcheck shell=bash disable=SC2034
# (SC2034: globals set here are read by the other sourced modules.)
# Renders the deployable manifest set without touching tracked files and without contacting the
# cluster. demo.sh writes a kustomization into the git-ignored .maop/render/<namespace>/ tree that
#   - references the chosen overlay (openshift | openshift-cma | kubernetes),
#   - sets the namespace and image references (kustomize `images:`),
#   - merges deploy-time values into maop-config / model-config,
#   - generates ConfigMap opa-policy from policy/maop/ (kustomize may only read files below the
#     kustomization root, so the policy files are copied next to the generated kustomization),
#   - patches ScaledObject bounds, the KEDA/CMA endpoint namespace, ingress hosts, exposure,
#   - and renders the cluster-scoped ClusterSPIFFEID separately (no namespace transform).
#
# Inputs (globals): MAOP_PLATFORM MAOP_NAMESPACE MAOP_PROFILE R_SCALER R_TRUST_DOMAIN R_CLASS_NAME
#   R_JAEGER_URL R_GRAFANA_URL, image refs from image_ref(), MAOP_* config.

# Policy files that go into the opa-policy ConfigMap: every non-test .rego and data.json.
policy_files() {
  local dir="${REPO_ROOT}/policy/maop" f
  [[ -d "$dir" ]] || return 0
  for f in "$dir"/*.rego "$dir"/data.json; do
    [[ -f "$f" ]] || continue
    case "$f" in *_test.rego) continue;; esac
    printf '%s\n' "$f"
  done
}

# Image reference for a service: from the last build record, else a placeholder (render only).
image_ref() {
  local svc="$1" var ref=""
  var="IMAGE_$(printf '%s' "$svc" | tr 'a-z-' 'A-Z_')"
  ref="${!var:-}"
  printf '%s\n' "${ref:-maop-${svc}:0.0.0-dev}"
}

image_record_file() { printf '%s/images-%s-%s.env\n' "$MAOP_STATE_DIR" "$MAOP_PLATFORM" "$MAOP_NAMESPACE"; }

load_image_record() {
  local f line
  f="$(image_record_file)"
  [[ -f "$f" ]] || return 1
  while IFS= read -r line; do
    [[ "$line" =~ ^(IMAGE_[A-Z_]+)=(.+)$ ]] || continue
    printf -v "${BASH_REMATCH[1]}" '%s' "${BASH_REMATCH[2]}"
  done < "$f"
  return 0
}

# kustomize `images:` entry for one service.
_images_entry() {
  local svc="$1" ref name rest
  ref="$(image_ref "$svc")"
  printf '  - name: maop-%s\n' "$svc"
  if [[ "$ref" == *@sha256:* ]]; then
    printf '    newName: %s\n    digest: %s\n' "${ref%@*}" "${ref#*@}"
  else
    rest="${ref##*/}"
    if [[ "$rest" == *:* ]]; then
      name="${ref%:*}"
      printf '    newName: %s\n    newTag: %s\n' "$name" "${ref##*:}"
    else
      printf '    newName: %s\n' "$ref"
    fi
  fi
}

_literal() { printf '      - %s\n' "$(json_str "$1=$2")"; }

render_overlay_name() {
  if [[ "$MAOP_PLATFORM" == "openshift" ]]; then
    [[ "${R_SCALER:-keda}" == "cma" ]] && echo openshift-cma || echo openshift
  else
    echo kubernetes
  fi
}

# render_manifests <output-file>
render_manifests() {
  local out="$1"
  local overlay root app idn rel profile_min=1
  overlay="$(render_overlay_name)"
  root="${MAOP_STATE_DIR}/render/${MAOP_NAMESPACE}"
  app="${root}/app"; idn="${root}/identity"
  rel="../../../.."   # from .maop/render/<ns>/{app,identity} to the repository root
  rm -rf "$root"; mkdir -p "$app/policy" "$idn"

  local td="${R_TRUST_DOMAIN:?trust domain not resolved}"
  local profile="${MAOP_PROFILE:-summit}"
  case "$profile" in summit|dev) ;; *) die "unknown profile: $profile (summit|dev)";; esac

  # --- policy -------------------------------------------------------------------------------
  local files=() f base
  while IFS= read -r f; do files+=("$f"); done < <(policy_files)
  if ((${#files[@]} == 0)); then
    if [[ "${OPT_ALLOW_MISSING_POLICY:-false}" == "true" ]]; then
      warn "policy/maop/ has no policy files; rendering with a deny-all PLACEHOLDER policy (render only)"
      printf 'package maop.tools\n\n# PLACEHOLDER generated by demo.sh render: policy/maop/ was empty.\ndefault decision := {"allow": false, "reasons": ["policy_missing"]}\n' > "$app/policy/tools.rego"
      printf '{"maop": {}}\n' > "$app/policy/data.json"
    else
      die "policy/maop/ contains no policy (*.rego, data.json); tool-service would fail closed on every call"
    fi
  else
    for f in "${files[@]}"; do cp "$f" "$app/policy/"; done
    # Bind the deployment's trust domain into the policy data when the source leaves it open
    # (data.json "trust_domain": ""), so OPA's trust-domain rule compares against the configured
    # domain (docs/security.md §4.3). The tracked file is not modified.
    if [[ -f "$app/policy/data.json" ]] && jq -e '.trust_domain == ""' "$app/policy/data.json" >/dev/null 2>&1; then
      jq --arg td "$td" '.trust_domain = $td' "$app/policy/data.json" > "$app/policy/data.json.tmp"
      mv "$app/policy/data.json.tmp" "$app/policy/data.json"
    fi
  fi

  # --- spiffe-helper socket override ---------------------------------------------------------
  local helper_override=false
  if [[ -n "${MAOP_SPIFFE_SOCKET_NAME:-}" && "$MAOP_SPIFFE_SOCKET_NAME" != "spire-agent.sock" ]]; then
    [[ "$MAOP_SPIFFE_SOCKET_NAME" =~ ^[A-Za-z0-9._-]+$ ]] || die "invalid MAOP_SPIFFE_SOCKET_NAME"
    sed "s#/spiffe-workload-api/spire-agent.sock#/spiffe-workload-api/${MAOP_SPIFFE_SOCKET_NAME}#" \
      "${REPO_ROOT}/deploy/components/spiffe/helper.conf" > "$app/helper.conf"
    helper_override=true
  fi

  # --- app kustomization ---------------------------------------------------------------------
  {
    printf '# GENERATED by demo.sh — do not edit; regenerated on every run.\n'
    printf 'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n'
    printf 'namespace: %s\n' "$MAOP_NAMESPACE"
    printf 'resources:\n  - %s/deploy/overlays/%s\n' "$rel" "$overlay"
    if [[ "$profile" == "dev" ]]; then
      printf 'components:\n  - %s/deploy/components/profile-dev\n' "$rel"
    fi

    printf 'images:\n'
    local svc
    for svc in $MAOP_SERVICES; do _images_entry "$svc"; done

    printf 'configMapGenerator:\n'
    printf '  - name: maop-config\n    behavior: merge\n    literals:\n'
    _literal MAOP_TRUST_DOMAIN "$td"
    _literal MAOP_TOOL_SERVICE_SPIFFE_ID "spiffe://${td}/ns/${MAOP_NAMESPACE}/sa/tool-service"
    _literal MAOP_PROFILE "$profile"
    _literal MAOP_EVIDENCE_MIN_REPLICAS "$profile_min"
    _literal MAOP_EVIDENCE_MAX_REPLICAS "$MAOP_EVIDENCE_MAX_REPLICAS"
    printf '  - name: model-config\n    behavior: merge\n    literals:\n'
    _literal MAOP_MODEL_MODE "$MAOP_MODEL_MODE"
    _literal MAOP_MODEL_BASE_URL "$MAOP_MODEL_BASE_URL"
    _literal MAOP_MODEL_NAME "$MAOP_MODEL_NAME"
    printf '  - name: opa-policy\n    options:\n      labels:\n        app.kubernetes.io/name: tool-service\n    files:\n'
    for f in "$app"/policy/*; do base="$(basename "$f")"; printf '      - %s=policy/%s\n' "$base" "$base"; done
    if [[ "$helper_override" == "true" ]]; then
      printf '  - name: spiffe-helper-config\n    behavior: replace\n    files:\n      - helper.conf\n'
    fi

    printf 'patches:\n'
    # ScaledObject bounds.
    printf '  - target: {group: keda.sh, kind: ScaledObject, name: evidence-worker}\n    patch: |-\n'
    printf '      - {op: replace, path: /spec/minReplicaCount, value: %s}\n' "$profile_min"
    printf '      - {op: replace, path: /spec/maxReplicaCount, value: %s}\n' "$MAOP_EVIDENCE_MAX_REPLICAS"
    # Policy volume items: every key mounted under maop/ (data.json -> data.maop).
    printf '  - target: {group: apps, kind: Deployment, name: tool-service}\n    patch: |-\n'
    printf '      apiVersion: apps/v1\n      kind: Deployment\n      metadata:\n        name: tool-service\n'
    printf '      spec:\n        template:\n          spec:\n            volumes:\n'
    printf '              - name: policy\n                configMap:\n                  name: opa-policy\n                  items:\n'
    for f in "$app"/policy/*; do
      base="$(basename "$f")"
      printf '                    - {key: %s, path: maop/%s}\n' "$base" "$base"
    done
    # Known external URLs (rerun keeps them instead of blanking).
    printf '  - patch: |-\n      apiVersion: v1\n      kind: ConfigMap\n      metadata:\n        name: ops-console-config\n      data:\n'
    printf '        MAOP_JAEGER_URL: %s\n' "$(json_str "${R_JAEGER_URL:-}")"
    printf '        MAOP_GRAFANA_URL: %s\n' "$(json_str "${R_GRAFANA_URL:-}")"
    if [[ "$MAOP_PLATFORM" == "kubernetes" ]]; then
      local name sub
      for name in ops-console jaeger grafana; do
        sub="$name"; [[ "$name" == "ops-console" ]] && sub="console"
        printf '  - target: {group: networking.k8s.io, kind: Ingress, name: %s}\n    patch: |-\n' "$name"
        printf '      - {op: replace, path: /spec/rules/0/host, value: %s}\n' "$(json_str "${sub}.${MAOP_INGRESS_DOMAIN}")"
        if [[ -n "$MAOP_INGRESS_CLASS" ]]; then
          printf '      - {op: add, path: /spec/ingressClassName, value: %s}\n' "$(json_str "$MAOP_INGRESS_CLASS")"
        fi
      done
    fi
    if [[ "$MAOP_EXPOSE_OBSERVABILITY" == "false" ]]; then
      local kind api
      if [[ "$MAOP_PLATFORM" == "openshift" ]]; then kind=Route; api=route.openshift.io/v1; else kind=Ingress; api=networking.k8s.io/v1; fi
      for name in jaeger grafana; do
        # shellcheck disable=SC2016  # literal kustomize directive
        printf '  - patch: |-\n      $patch: delete\n      apiVersion: %s\n      kind: %s\n      metadata:\n        name: %s\n' "$api" "$kind" "$name"
      done
    fi

    # Namespace-dependent strings: replace the second dot-separated segment with the
    # ScaledObject's (final) namespace. Replacements run after the namespace transformer.
    local field
    if [[ "$overlay" == "openshift-cma" ]]; then
      field="spec.triggers.0.metadata.serverAddress"     # http://prometheus.<ns>.svc:9090
    else
      field="spec.triggers.0.metadata.natsServerMonitoringEndpoint"   # nats.<ns>.svc.cluster.local:8222
    fi
    printf 'replacements:\n'
    printf '  - source: {group: keda.sh, kind: ScaledObject, name: evidence-worker, fieldPath: metadata.namespace}\n'
    printf '    targets:\n      - select: {group: keda.sh, kind: ScaledObject, name: evidence-worker}\n'
    printf '        fieldPaths: [%s]\n        options: {delimiter: ".", index: 1}\n' "$field"
  } > "$app/kustomization.yaml"

  # --- identity kustomization (cluster-scoped, no namespace) ---------------------------------
  {
    printf '# GENERATED by demo.sh — do not edit.\n'
    printf 'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n'
    printf 'resources:\n  - %s/deploy/base/identity\n' "$rel"
    printf 'patches:\n  - target: {group: spire.spiffe.io, kind: ClusterSPIFFEID}\n    patch: |-\n'
    printf '      - {op: replace, path: /metadata/name, value: %s}\n' "$(json_str "maop-${MAOP_NAMESPACE}")"
    printf '      - {op: replace, path: /spec/namespaceSelector/matchLabels/kubernetes.io~1metadata.name, value: %s}\n' "$(json_str "$MAOP_NAMESPACE")"
    if [[ -n "${R_CLASS_NAME:-}" ]]; then
      printf '      - {op: replace, path: /spec/className, value: %s}\n' "$(json_str "$R_CLASS_NAME")"
    else
      printf '      - {op: remove, path: /spec/className}\n'
    fi
  } > "$idn/kustomization.yaml"

  local kz=(kubectl kustomize)
  if ! have kubectl; then kz=(oc kustomize); fi
  {
    "${kz[@]}" "$app"
    printf -- '---\n'
    "${kz[@]}" "$idn"
  } > "$out" || die "kustomize rendering failed (generated sources in ${root})"
}

# ./demo.sh render — offline rendering (no cluster access). Uses the last build record for image
# references when one exists, placeholders otherwise.
cmd_render() {
  R_SCALER="$OPT_SCALER"
  [[ "$MAOP_PLATFORM" == "kubernetes" && "$R_SCALER" == "cma" ]] && die "--scaler cma applies to --platform openshift only"
  R_TRUST_DOMAIN="${OPT_TRUST_DOMAIN:-${MAOP_SPIRE_TRUST_DOMAIN:-maop.example}}"
  R_CLASS_NAME="${MAOP_SPIRE_CLASS_NAME:-$SPIRE_CLASS_NAME}"
  R_JAEGER_URL=""; R_GRAFANA_URL=""
  OPT_ALLOW_MISSING_POLICY=true
  load_image_record || true
  local tmp out
  tmp="$(maop_tmpdir)"
  out="${OPT_OUTPUT:-$tmp/rendered.yaml}"
  render_manifests "$out"
  if [[ -z "$OPT_OUTPUT" ]]; then cat "$out"; else log "wrote $out"; fi
}
